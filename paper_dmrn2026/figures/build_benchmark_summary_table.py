"""Write Table 1 (benchmark-table.tex) from the four benchmark result files in this folder.

    python figures/build_benchmark_summary_table.py

Rows, each from one benchmark job on the cluster's rdg hosts (A100 80 GB; job number in the file name):
    Auto (compiled)   fdtd_jax             native-rate-jit-jax-grid-plain-rdg-35747154.json
    + checkpoints     fdtd_jax_ckpt        native-rate-jit-jax-grid-ckpt-rdg-35747153.json
    + modes           fdtd_jax_sine_ckpt   native-rate-jit-jax-sine-ckpt-rdg-35746438.json
    Hand-written      replay               native-rate-replay-rdg-35746439.json
Each batch column is shaded in equal steps between the distinct values shown, per metric; the best value
of each column is bold, and a run out of the A100's memory is a dash.
"""

import json
from pathlib import Path

FOLDER = Path(__file__).resolve().parent
ROWS = [
    ("Auto (compiled)", "fdtd_jax", "native-rate-jit-jax-grid-plain-rdg-35747154.json"),
    (r"\step\,+ checkpoints", "fdtd_jax_ckpt", "native-rate-jit-jax-grid-ckpt-rdg-35747153.json"),
    (r"\step\,+ modes", "fdtd_jax_sine_ckpt", "native-rate-jit-jax-sine-ckpt-rdg-35746438.json"),
    ("Hand-written", "replay", "native-rate-replay-rdg-35746439.json"),
]
METRICS = [("Peak memory (GB)", "peak_gpu_bytes", 1e-9), ("Iteration time (s)", "median_seconds", 1)]


def measurements(method, filename):
    data = json.loads((FOLDER / filename).read_text())
    assert data["metadata"]["status"] == "complete" and not data["metadata"].get("source_changed_during_run")
    rows = {row["batch"]: row for row in data["rows"] if row["method"] == method}
    return data["metadata"]["batch_sizes"], rows


def cell(row, field, factor):
    if row["status"] != "ok":
        assert row["status"] == "oom", row["status"]
        return "-"
    value = row[field] * factor
    if factor != 1:
        return f"{value:.1f}"
    return f"{value:.2f}" if value < 10 else f"{value:.1f}" if value < 100 else f"{value:.0f}"


def main():
    loaded = [(name, *measurements(method, filename)) for name, method, filename in ROWS]
    batches = loaded[0][1]
    assert all(sizes == batches and sorted(rows) == batches for _, sizes, rows in loaded)
    lines = [
        r"\begin{tabular}{@{}l*{8}{c}}",
        r" & \multicolumn{8}{c}{Batch Size}\\",
        "Method & " + " & ".join(map(str, batches)) + r"\\",
        r"\hline",
    ]
    for label, field, factor in METRICS:
        lines += [r"\noalign{\vskip 2pt}", r" & \multicolumn{8}{c}{" + label + r"}\\[2pt]"]
        table = [(name, [cell(rows[b], field, factor) for b in batches]) for name, _, rows in loaded]
        shown = [[float(c) for c in cells if c != "-"] for _, cells in table]
        best = [min(float(cells[i]) for _, cells in table if cells[i] != "-") for i in range(len(batches))]
        distinct = sorted({value for values in shown for value in values})
        shade = {value: 100 * rank / (len(distinct) - 1) for rank, value in enumerate(distinct)}
        for name, cells in table:
            formatted = []
            for i, text in enumerate(cells):
                if text == "-":
                    formatted.append(r"\cellcolor{heatpurple}\textemdash")
                    continue
                value = float(text)
                body = r"\textbf{" + text + "}" if value == best[i] else text
                colour = r"\cellcolor{heatpurple!" + f"{shade[value]:.2f}" + "}" if shade[value] > 0 else ""
                formatted.append(colour + body)
            lines.append(name + " & " + " & ".join(formatted) + r"\\")
        lines.append(r"\noalign{\vskip 2pt}\cline{2-9}" if factor != 1 else r"\hline")
    lines.append(r"\end{tabular}")
    output = FOLDER / "benchmark-table.tex"
    header = "% Generated by build_benchmark_summary_table.py from the four benchmark files it names\n"
    output.write_text(header + "\n".join(lines) + "\n")
    print("Wrote", output)


if __name__ == "__main__":
    main()
