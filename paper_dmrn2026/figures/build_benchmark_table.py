"""Heat-map benchmark table from a completed native-rate sweep.

Usage: build_benchmark_table.py [sweep.json] [output.tex] [saturate-ratio | rank]

Writes a LaTeX tabular with batch sizes as columns and two blocks of three
rows, each introduced by a full-width label row: Ours (``cached3``),
jaxdiffmodal (``diaz_44100`` at the sweep's primary mode count) and Autodiff
(``fdtd``), first for median seconds per evaluation, then for peak sampled
GPU memory in GB. Each block is shaded on its own,
from white at the best measured value to purple at the worst, interpolated
on a log scale between the block's extremes, or, when a saturate ratio is
given, between the best and that multiple of it (anything beyond is full
purple), or, with ``rank``, by the order of the printed values alone so that
cells showing the same number share a shade and neighbouring ranks differ by
the same step whatever their gap; a failed batch prints its recorded status
at full shade. The including document needs xcolor with the
``table`` option and ``\\definecolor{tabpurple}``.
"""
import json
import math
from pathlib import Path
import sys

folder = Path(__file__).resolve().parent
source = Path(sys.argv[1]) if len(sys.argv) > 1 else folder/'native-rate-sweep-34855605.json'
output = Path(sys.argv[2]) if len(sys.argv) > 2 else folder/'benchmark-table.tex'
RANK = len(sys.argv) > 3 and sys.argv[3] == 'rank'
SATURATE = float(sys.argv[3]) if len(sys.argv) > 3 and not RANK else None
data = json.loads(source.read_text())
metadata = data['metadata']
if metadata['status'] != 'complete' or metadata.get('source_changed_during_run'):
    raise ValueError('The measurement is incomplete or source hashes changed')
batches = tuple(metadata['batch_sizes'])
primary = metadata.get('primary_modal_modes') or metadata['native_modal_modes'][0]
rows = data['rows']
STATUS = {'oom': 'OOM', 'host_memory_limit': 'host', 'timeout': 'time', 'error': 'err.'}
WHITE_TEXT_ABOVE = 55      # percent of purple beyond which the cell text turns white


def select(method, modes=None):
    found = {}
    for row in rows:
        if row.get('method') == method and (modes is None or row.get('modes') == modes):
            if row['batch'] in found:
                raise ValueError(f'duplicate result: {method} {modes} {row["batch"]}')
            found[row['batch']] = row
    if set(found) != set(batches):
        raise ValueError(f'missing batches for {method} {modes}: {set(batches)-set(found)}')
    return [found[b] for b in batches]


methods = (('Ours', select('cached3')),
           ('\\texttt{jaxdiffmodal}', select('diaz_44100', primary)),
           ('Autodiff', select('fdtd')))
seconds = lambda r: r['median_seconds']
gigabytes = lambda r: r['peak_gpu_bytes']/1e9
time_text = lambda v: f'{v:.2f}' if v < 10 else f'{v:.0f}'
memory_text = lambda v: f'{v:.1f}'


def block(label, value, text):
    measured = [value(r) for _, seq in methods for r in seq if r['status'] == 'ok']
    low = math.log(min(measured))
    high = low + math.log(SATURATE) if SATURATE else math.log(max(measured))
    shown = sorted({text(v) for v in measured}, key=float)          # distinct printed values, ascending
    lines = [f' & \\multicolumn{{{len(batches)}}}{{c}}{{\\textit{{{label}}}}}\\\\']
    for name, seq in methods:
        cells = []
        for r in seq:
            if r['status'] == 'ok':
                body = text(value(r))
                if RANK:
                    shade = round(100*shown.index(body)/len(shown))   # failures take the last rank
                else:
                    shade = min(100, round(100*(math.log(value(r))-low)/(high-low)))
            else:
                shade, body = 100, STATUS.get(r['status'], r['status'])
            if shade > WHITE_TEXT_ABOVE:
                body = f'\\textcolor{{white}}{{{body}}}'
            cells.append(f'\\cellcolor{{tabpurple!{shade}}}{body}')
        lines.append(f'{name} & ' + ' & '.join(cells) + '\\\\')
    return lines


head = ['\\begin{tabular}{@{}l*{%d}{r}@{}}' % len(batches), '\\hline',
        'Batch & ' + ' & '.join(str(b) for b in batches) + '\\\\', '\\hline']
body = block('Time (s)', seconds, time_text) + ['\\hline'] + block('Memory (GBs)', gigabytes, memory_text)
tail = ['\\hline', '\\end{tabular}']
output.write_text('% generated by build_benchmark_table.py from ' + source.name + '\n' + '\n'.join(head + body + tail) + '\n')
print('Wrote', output)
